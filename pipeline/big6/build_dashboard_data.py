"""Step 6 - serve: bundle the processed tables into one payload the static dashboard loads.

Tables are stored column-wise ({columns, rows}) rather than as repeated objects, which
roughly halves the file. The page rebuilds the row objects when it starts.
"""
import json

from common import DATA_AS_OF, PROCESSED, SITE_PAYLOAD, SOURCE_COMMIT, read_json
from validate import DATASETS


def columnar(rows):
    cols = list(rows[0].keys()) if rows else []
    return {"columns": cols, "rows": [[r.get(c) for c in cols] for r in rows]}


def main():
    payload = {
        "as_of": DATA_AS_OF,
        "transfermarkt_commit": SOURCE_COMMIT,
        "datasets": {name: columnar(read_json(PROCESSED / f"{name}.json")) for name in DATASETS},
    }
    SITE_PAYLOAD.parent.mkdir(parents=True, exist_ok=True)
    body = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    SITE_PAYLOAD.write_text(
        "/* Generated by pipeline/big6/build_dashboard_data.py from data/big6/processed. Do not edit by hand. */\n"
        f"window.BIG6_DATA = {body};\n",
        encoding="utf-8",
    )
    print(f"  serve: wrote {SITE_PAYLOAD.relative_to(SITE_PAYLOAD.parents[2])} ({SITE_PAYLOAD.stat().st_size / 1024:,.0f} KB)")


if __name__ == "__main__":
    main()
